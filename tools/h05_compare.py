def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--outdir", default=os.path.join(REPO_ROOT, OUTDIR_REL))
    ap.add_argument("--gen-tables", action="store_true",
                    help="regenerate the alg table hex + sha-pin manifest")
    ap.add_argument("--check-tables", action="store_true",
                    help="verify the committed table artifact only")
    ap.add_argument("--gen-only", action="store_true",
                    help="write program + gen report, no simulation")
    ap.add_argument("--skip-mutants", action="store_true",
                    help="run only the clean conformance build")
    ap.add_argument("--mutate-only", choices=sorted(MUTANTS), default=None,
                    help="run only one negative-control mutant build")
    ap.add_argument("--iverilog", default="iverilog")
    ap.add_argument("--vvp", default="vvp")
    args = ap.parse_args(argv)

    if args.gen_tables:
        gen_tables(os.path.dirname(os.path.join(REPO_ROOT, HEX_REL)))
        print("h05_compare: wrote %s + %s"
              % (HEX_REL, MANIFEST_REL))
        return 0
    if args.check_tables:
        try:
            manifest = check_tables()
        except CheckFailure as exc:
            print(f"FAIL: {exc}", file=sys.stderr)
            return 1
        print("h05_compare: table artifact byte-identical to the model "
              "(sha256 %s...)" % manifest["sha256"][:12])
        return 0

    try:
        manifest = check_tables()
    except CheckFailure as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1

    try:
        program, stream, meta, stats = golden()
    except Exception as exc:
        print(f"COULD-NOT-RUN: golden generation failed: {exc}",
              file=sys.stderr)
        return 2
    if stats["evals"] < MIN_EVALS:
        print(f"FAIL: run set has {stats['evals']} evals < required "
              f"{MIN_EVALS}", file=sys.stderr)
        return 1

    os.makedirs(args.outdir, exist_ok=True)
    program_path = os.path.join(args.outdir, "program.txt")
    with open(program_path, "w", encoding="ascii") as f:
        f.write("\n".join(program) + "\n")

    if args.gen_only:
        report = {
            "schema": "h05-gen-report/1",
            "issue": 27,
            "planning_id": "H05",
            "golden": "src/gf180_dx7/model/algorithm.py "
                      "(gf180-dx7-integer-v1)",
            "table_artifact": {"hex": HEX_REL, "manifest": MANIFEST_REL,
                               "sha256": manifest["sha256"]},
            "stats": stats,
            "program_sha256": sha256_file(program_path),
            "stream_sha256": hashlib.sha256(
                "\n".join(stream).encode("ascii")).hexdigest(),
        }
        with open(os.path.join(args.outdir, "gen_report.json"), "w",
                  encoding="utf-8") as f:
            json.dump(report, f, indent=1, sort_keys=True)
            f.write("\n")
        print(f"h05_compare: generated {stats['runs']} runs "
              f"({stats['evals']} evals, {stats['frames']} frames) "
              f"-> {program_path}")
        return 0

    try:
        ident = tool_identity(args.iverilog)
    except CouldNotRun as exc:
        print(f"COULD-NOT-RUN: {exc}", file=sys.stderr)
        return 2

    expected_rows = parse_stream_expected(stream)
    report = {
        "schema": "h05-compare-report/1",
        "issue": 27,
        "planning_id": "H05",
        "claim_boundary": "RTL-vs-frozen-model bit-exactness of the "
                          "algorithm routing/feedback layer only; no "
                          "synthesis, timing, fit, or audibility claim; "
                          "operator kernel arithmetic is H01's scope",
        "tool_identity": {
            "iverilog": ident,
            "python": sys.version.split()[0],
            "rtl": {p: sha256_file(os.path.join(REPO_ROOT, p))
                    for p in (RTL_REL, TB_REL)},
            "table_artifact": {"hex": HEX_REL, "manifest": MANIFEST_REL,
                               "sha256": manifest["sha256"]},
        },
        "vector_stats": stats,
        "program_sha256": sha256_file(program_path),
        "stream_sha256": hashlib.sha256(
            "\n".join(stream).encode("ascii")).hexdigest(),
        "mutants": {},
    }

    status = "PASS"
    try:
        if not args.mutate_only:
            workdir = tempfile.mkdtemp(prefix="h05_sim_")
            try:
                actual_path, sim_meta = run_sim(
                    args.iverilog, args.vvp, None, program_path, workdir)
                actual_rows = parse_stream(actual_path)
            finally:
                shutil.rmtree(workdir, ignore_errors=True)
            count, first, per_run = compare_streams(expected_rows,
                                                    actual_rows, meta)
            failed_runs = sum(1 for r in per_run if r["status"] == "FAIL")
            matrix_fail = sum(
                1 for r, m in zip(per_run, meta)
                if r["status"] == "FAIL" and m["kind"] == "matrix")
            ok = (count == 0 and failed_runs == 0
                  and sim_meta["bench_evals"] == stats["evals"])
            report["conformance"] = dict(
                sim_meta,
                expected_records=len(expected_rows),
                actual_records=len(actual_rows),
                mismatch_records=count,
                failed_runs=failed_runs,
                failed_matrix_runs=matrix_fail,
                per_run=per_run,
                first_mismatch=first,
                status="PASS" if ok else "FAIL",
            )
            status = "PASS" if ok else "FAIL"

        if not args.skip_mutants and not args.mutate_only:
            for name in sorted(MUTANTS):
                res = run_mutant(args, name, program_path, expected_rows,
                                 meta, stats)
                report["mutants"][name] = res
                if not res["met"]:
                    status = "FAIL"

        if args.mutate_only:
            res = run_mutant(args, args.mutate_only, program_path,
                             expected_rows, meta, stats)
            report["mutants"][args.mutate_only] = res
            status = "PASS" if res["met"] else "FAIL"
    except CouldNotRun as exc:
        print(f"COULD-NOT-RUN: {exc}", file=sys.stderr)
        return 2
    except CheckFailure as exc:
        report["status"] = "FAIL"
        report["error"] = str(exc)
        with open(os.path.join(args.outdir, "compare_report.json"), "w",
                  encoding="utf-8") as f:
            json.dump(report, f, indent=1, sort_keys=True)
            f.write("\n")
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1

    if args.skip_mutants:
        status = "PASS" if report["conformance"]["status"] == "PASS" \
            else "FAIL"
    report["status"] = status
    with open(os.path.join(args.outdir, "compare_report.json"), "w",
              encoding="utf-8") as f:
        json.dump(report, f, indent=1, sort_keys=True)
        f.write("\n")

    if "conformance" in report:
        cf = report["conformance"]
        print(f"conformance: {cf['status']} "
              f"({stats['runs']} runs / {stats['evals']} evals, "
              f"{cf['mismatch_records']} mismatching records, "
              f"{cf['failed_runs']} failing runs)")
        fm = cf["first_mismatch"]
        if fm:
            print("  first mismatch: run %s alg %s fb %s: expected %r "
                  "got %r" % (fm.get("run"), fm.get("algorithm"),
                              fm.get("feedback"), fm.get("expected"),
                              fm.get("actual")))
    for name, res in report["mutants"].items():
        print("negative control %s: %s" % (name, res["status"]))
    print(f"report: {os.path.join(args.outdir, 'compare_report.json')}")
    return 0 if status == "PASS" else 1


def parse_stream_expected(stream):
    return [(0, line.split()) for line in stream if line]


def run_mutant(args, name, program_path, expected_rows, meta, stats):
    define, description = MUTANTS[name]
    workdir = tempfile.mkdtemp(prefix="h05_mut_")
    try:
        actual_path, sim_meta = run_sim(args.iverilog, args.vvp, name,
                                        program_path, workdir)
        actual_rows = parse_stream(actual_path)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    count, first, per_run = compare_streams(expected_rows, actual_rows,
                                            meta)
    failed = [i for i, r in enumerate(per_run) if r["status"] == "FAIL"]
    failed_algs = sorted({meta[i]["algorithm"] for i in failed})
    failed_fb_pos = [meta[i] for i in failed]
    if name == "oporder":
        met = len(failed_algs) >= 28
        detail = {"failed_algorithms": failed_algs,
                  "failed_algorithm_count": len(failed_algs)}
    else:
        # every feedback>0 run with a live feedback path must fail;
        # runs whose fb op is gate-skipped (fb_inert) carry no feedback
        # term, and feedback-0 runs never read the history -- those
        # legitimately survive a feedback-only defect.
        fb_pos_runs = [i for i, m in enumerate(meta)
                       if m["feedback"] > 0 and not m["fb_inert"]]
        missing = [i for i in fb_pos_runs if i not in set(failed)]
        met = not missing
        detail = {"failed_runs": len(failed),
                  "feedback_positive_runs": len(fb_pos_runs),
                  "surviving_feedback_positive_runs": missing[:8]}
    res = {
        "define": define,
        "description": description,
        "mismatch_records": count,
        "first_mismatch": first,
        **detail,
        "status": ("MET (mutant fails conformance as required)" if met
                   else "NOT MET (mutant passed -- harness has no "
                        "resolution)"),
        "met": met,
    }
    return res


