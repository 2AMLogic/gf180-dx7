#!/usr/bin/env python3
"""H05 routing/feedback RTL conformance harness (issue #27).

The golden is the FROZEN PYTHON MODEL (src/gf180_dx7/model/algorithm.py,
contract gf180-dx7-integer-v1); the device under test is the RTL
(rtl/alg_router.v). The bar is bit-exactness -- no tolerance: any mismatch
means the RTL (or its table bytes) is wrong, never a loosened check.

Table artifact (parasynth gen_tables discipline, docs/REUSE-RULINGS.md):
`--gen-tables` regenerates reference/tables/alg_table.hex FROM the model's
ALGORITHMS table (fm_core.cc:29-62 facts) plus a manifest pinning its
SHA-256, so the Python model and the RTL's $readmemh share ONE table
artifact. `--check-tables` re-runs the generation in memory and fails on
any drift; every compare run performs the check before simulating, so a
mutated hex never silently becomes the shared artifact.

Conformance flow:
  1. build the directed run set from the model: ALL 32 algorithms x
     feedback {0, 3, 7} x 3 frames (scripted operator sources, block-level
     feedback recirculation across frames) plus directed fb-history-seed,
     fb-off-untouched and gating/has_contents runs (>= 6000 evals);
  2. drive rtl/tb_alg_router.v under iverilog; the bench streams the eval
     records (op, phase_in, gain, mod) and the per-frame note outputs and
     state readouts; the Python comparator judges bit-exact with
     first-mismatch localization (run, eval index, algorithm, op);
  3. NEGATIVE CONTROLS (issue #27): rebuild the RTL with
     -DH05_MUTATE_OP_ORDER (operator state addressing permuted; must fail
     on >= 28 of 32 algorithms), -DH05_INVERT_FB_SIGN (feedback term
     sign-flipped; every feedback>0 run must fail) and
     -DH05_DELAY_FB_COMMIT (history committed one block late; every
     feedback>0 run must fail) -- each mutant MUST fail the check it
     targets, proving the harness has resolution.

Exit codes: 0 pass, 1 check failure (clean-run mismatch, control not met,
or table drift), 2 could-not-run (missing iverilog/vvp; message names it).
Stdlib only.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO_ROOT, "src")
if SRC not in sys.path:
    sys.path.insert(0, SRC)

from gf180_dx7.model.algorithm import (  # noqa: E402
    ALGORITHMS, AlgorithmRouter, FmParams, decode_op, fb_shift_for)

RTL_REL = "rtl/alg_router.v"
TB_REL = "rtl/tb_alg_router.v"
OUTDIR_REL = "evidence/h05-routing-rtl"
HEX_REL = "reference/tables/alg_table.hex"
MANIFEST_REL = "reference/tables/alg_manifest.json"
MIN_EVALS = 6000

U32 = 0xFFFFFFFF

# Scripted source (the model's sin_fn seam): op k's output at global eval
# index t with modulation term m, wrapped to int32 like a real kernel.
BASE = [110 * (k + 1) for k in range(6)]
STEP = [7 * k + 3 for k in range(6)]
WMUL = 3

# Scenario constants mirroring tests/test_algorithm.py (N04 battery).
PARKED_LEVEL = 15360 << 14      # gain2 = ENV_MAX - 15360 = 1024
GATED_LEVEL = 16 << 16          # gain2 = 16320 > 16284 -> gate-skipped
FRAMES = 3

FB_SETTINGS = (0, 3, 7)


class CheckFailure(Exception):
    pass


class CouldNotRun(Exception):
    pass


def w32(v: int) -> int:
    v &= U32
    return v - (1 << 32) if v >= (1 << 31) else v


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


# ---------------------------------------------------------------------------
# The shared table artifact (generated; sha-pinned; model == RTL bytes)
# ---------------------------------------------------------------------------

def build_alg_hex() -> str:
    lines = [
        "// h05 algorithm connection table (issue #27)",
        "// GENERATED by tools/h05_compare.py --gen-tables from the FROZEN",
        "// model table src/gf180_dx7/model/algorithm.py ALGORITHMS",
        "// (fm_core.cc:29-62 facts) so the Python model and this RTL ROM",
        "// share ONE table artifact (parasynth gen_tables discipline).",
        "// 32 rows x 6 op descriptors, one byte per op, row-major op 0..5.",
        "// sha256 pinned in reference/tables/alg_manifest.json; verified",
        "// by --check-tables before every simulation. DO NOT hand-edit.",
    ]
    for row in ALGORITHMS:
        lines.append(" ".join("%02x" % f for f in row))
    return "\n".join(lines) + "\n"


def build_alg_manifest(hex_text: str) -> dict:
    return {
        "schema": "gf180-dx7/table-manifest-v1",
        "table": "alg_table",
        "entries": 192,
        "bits": 8,
        "generator": "tools/h05_compare.py --gen-tables",
        "source": "src/gf180_dx7/model/algorithm.py ALGORITHMS "
                  "(fm_core.cc:29-62 facts); regenerated, never copied "
                  "(NUM-001); parasynth gen_tables discipline",
        "issue": "https://github.com/2AMLogic/gf180-dx7/issues/27",
        "sha256": hashlib.sha256(hex_text.encode("ascii")).hexdigest(),
    }


def gen_tables(outdir: str) -> None:
    hex_text = build_alg_hex()
    hex_path = os.path.join(outdir, "alg_table.hex")
    with open(hex_path, "w", encoding="ascii") as f:
        f.write(hex_text)
    with open(os.path.join(outdir, "alg_manifest.json"), "w",
              encoding="utf-8") as f:
        json.dump(build_alg_manifest(hex_text), f, indent=2, sort_keys=True)
        f.write("\n")


def check_tables(repo_root: str | None = None, hex_path: str | None = None,
                 manifest_path: str | None = None) -> dict:
    """Regenerate in memory and verify the committed bytes + manifest pin.

    Raises CheckFailure on any drift (hand-edit, mutation, stale manifest).
    """
    root = repo_root or REPO_ROOT
    hp = hex_path or os.path.join(root, HEX_REL)
    mp = manifest_path or os.path.join(root, MANIFEST_REL)
    hex_text = build_alg_hex()
    if not os.path.isfile(hp):
        raise CheckFailure(f"missing generated table artifact: {hp}")
    with open(hp, "r", encoding="ascii") as f:
        committed = f.read()
    if committed != hex_text:
        raise CheckFailure(
            f"{hp}: bytes drifted from regeneration of "
            "src/gf180_dx7/model/algorithm.py ALGORITHMS (sha-pin check "
            "FAILED -- the model/RTL shared table artifact is corrupt)")
    if not os.path.isfile(mp):
        raise CheckFailure(f"missing table manifest: {mp}")
    with open(mp, "r", encoding="utf-8") as f:
        manifest = json.load(f)
    expected = build_alg_manifest(hex_text)
    if manifest != expected:
        raise CheckFailure(
            f"{mp}: manifest drifted from regeneration (sha-pin check "
            "FAILED)")
    return manifest


# ---------------------------------------------------------------------------
# Golden generation: drive the FROZEN model with the scripted source
# ---------------------------------------------------------------------------

def fb_op_index(alg: int) -> int:
    """The one feedback-loop op of a row ((flags & 0xC0) == 0xC0)."""
    for k in range(6):
        if decode_op(ALGORITHMS[alg][k])[3]:
            return k
    raise CheckFailure(f"algorithm {alg + 1} has no feedback op")


def scenarios():
    """The directed run set: (name, alg 0-based, feedback, per-op level_in,
    fb seed, fb_inert). Deterministic; the matrix is 32 x {0,3,7}.

    fb_inert marks runs whose feedback op is gate-skipped: no feedback
    path is exercised, so feedback-sign/delay mutants are provably
    invisible there and the mutant controls exclude them.
    """
    runs = []
    parked = [PARKED_LEVEL] * 6
    for alg in range(32):
        for fb in FB_SETTINGS:
            runs.append(("matrix", alg, fb, parked, (0, 0), False))
    # fb-history seeds: frame-start read path, depth-2 window, +2 shifts.
    seed = (0, 1 << 20)
    for alg in (0, 3, 5, 7, 27, 31):
        for fb in (3, 7):
            runs.append(("fb-seed", alg, fb, parked, seed, False))
    # fb off must leave the history untouched.
    for alg in (7, 31):
        runs.append(("fb-off-untouched", alg, 0, parked, (12345, -6789),
                     False))
    # gating / has_contents scenarios (N04's list) at feedback 7.
    gated_scenarios = [
        (0, (0,)),    # ALG 1: fb op gated; chain falls back to pure
        (6, (0, 1)),  # ALG 7: op2's bus-add forced off
        (15, (2,)),   # ALG 16: bus2 writer gated -> pure add onto bus1
        (3, (0,)),    # ALG 4: serial skipped, generic per-op path
        (5, (0,)),    # ALG 6: serial skipped, generic per-op path
        (31, (0,)),   # ALG 32: gated add carrier
    ]
    for alg, gated in gated_scenarios:
        levels = [GATED_LEVEL if k in gated else PARKED_LEVEL
                  for k in range(6)]
        runs.append(("gated", alg, 7, levels, (0, 0),
                     fb_op_index(alg) in set(gated)))
    return runs


def golden():
    """Run the FROZEN model over every scenario.

    Returns (program_lines, stream_lines, runs_meta, stats). stream_lines
    mirrors exactly what the bench emits: A markers, per-eval E records
    (op, phase_in, gain, mod), per-frame O (64 note outputs) and Q
    (6 phases, 6 gain_out, fb0, fb1) records.
    """
    program = [
        "# h05 routing/feedback directed program (issue #27)",
        "# generated by tools/h05_compare.py from the FROZEN model",
        "# src/gf180_dx7/model/algorithm.py "
        "(contract gf180-dx7-integer-v1)",
        "# table artifact: reference/tables/alg_table.hex "
        "(alg_manifest.json sha-pin)",
        "# A <alg hex2> <fb hex1>       new run (bench resets the DUT)",
        "# P <idx> <phase8> <freq8> <level8> <gain4>   load op params",
        "# F <fb0 hex8> <fb1 hex8>      load committed fb history",
        "# S                            render one 64-sample frame",
    ]
    stream = []
    meta = []
    total_evals = 0
    for idx, (kind, alg, fb, levels, fb_seed, fb_inert) in \
            enumerate(scenarios()):
        params = [FmParams() for _ in range(6)]
        for k, p in enumerate(params):
            p.freq = 1000 * (k + 1)
            p.level_in = levels[k]
        router = AlgorithmRouter(None, None)  # fresh buses per run
        fb_buf = list(fb_seed)
        calls = []

        def sin_fn(op, i, phase_plus, gain, mod):
            t = len(calls)
            m = w32(mod)
            y = w32(BASE[op] + t * STEP[op] + WMUL * m)
            calls.append((op, t, phase_plus & U32, gain & 0xFFFF,
                          m & U32, y & U32))
            return y

        shift = fb_shift_for(fb)
        program.append("A %02x %x" % (alg, fb))
        for k, p in enumerate(params):
            program.append("P %x %08x %08x %08x %04x"
                           % (k, p.phase & U32, p.freq & U32,
                              p.level_in & U32, p.gain_out & U32))
        program.append("F %08x %08x" % (fb_seed[0] & U32,
                                        fb_seed[1] & U32))
        stream.append("A %x %x" % (alg, fb))
        run_evals = 0
        for _frame in range(FRAMES):
            program.append("S")
            out = [0] * 64
            before = len(calls)
            router.render(out, params, alg, fb_buf, shift, sin_fn=sin_fn)
            for (op, _t, phase_in, gain, mod, _y) in calls[before:]:
                stream.append("E %x %08x %04x %08x"
                              % (op, phase_in, gain, mod))
            run_evals += len(calls) - before
            for v in out:
                stream.append("O %08x" % (v & U32))
            for p in params:
                stream.append("Q %08x" % (p.phase & U32))
            for p in params:
                stream.append("Q %08x" % (p.gain_out & U32))
            stream.append("Q %08x" % (fb_buf[0] & U32))
            stream.append("Q %08x" % (fb_buf[1] & U32))
        total_evals += run_evals
        meta.append({"run": idx, "kind": kind, "algorithm": alg + 1,
                     "feedback": fb, "frames": FRAMES, "evals": run_evals,
                     "fb_inert": fb_inert})
    stats = {
        "runs": len(meta),
        "matrix_runs": sum(1 for m in meta if m["kind"] == "matrix"),
        "directed_runs": sum(1 for m in meta if m["kind"] != "matrix"),
        "frames": sum(m["frames"] for m in meta),
        "evals": total_evals,
        "min_evals_required": MIN_EVALS,
        "algorithms": 32,
        "feedback_settings": list(FB_SETTINGS),
    }
    return program, stream, meta, stats


# ---------------------------------------------------------------------------
# Comparator: bit-exact with first-mismatch localization
# ---------------------------------------------------------------------------

def parse_stream(path):
    rows = []
    with open(path, "r", encoding="ascii") as f:
        for lineno, raw in enumerate(f, 1):
            line = raw.strip()
            if not line:
                continue
            rows.append((lineno, line.split()))
    return rows


def compare_streams(expected_rows, actual_rows, runs_meta):
    """Record-by-record bit-exact compare.

    Returns (mismatch_count, first_mismatch, per_run) where first_mismatch
    localizes (run index, algorithm, feedback, record kind, eval index, op).
    """
    first = None
    count = 0
    per_run = [{"status": "PASS", "mismatches": 0} for _ in runs_meta]
    run_of = []
    for i, m in enumerate(runs_meta):
        # stream records per run: 1 A marker + evals + frames*(64 O + 14 Q)
        run_of += [i] * (1 + m["evals"] + m["frames"] * (64 + 14))
    n = max(len(expected_rows), len(actual_rows))
    for k in range(n):
        if k >= len(expected_rows) or k >= len(actual_rows):
            count += 1
            if first is None:
                ridx = run_of[min(k, len(run_of) - 1)]
                m = runs_meta[ridx]
                first = {
                    "run": ridx, "algorithm": m["algorithm"],
                    "feedback": m["feedback"],
                    "error": "row-count mismatch: expected %d records, "
                             "RTL emitted %d" % (len(expected_rows),
                                                 len(actual_rows)),
                }
            break
        _, e = expected_rows[k]
        _, a = actual_rows[k]
        if e == a:
            continue
        count += 1
        ridx = run_of[k] if k < len(run_of) else -1
        if ridx >= 0:
            per_run[ridx]["status"] = "FAIL"
            per_run[ridx]["mismatches"] += 1
        if first is None:
            m = runs_meta[ridx] if ridx >= 0 else {}
            rec = {
                "line_expected": expected_rows[k][0],
                "line_actual": actual_rows[k][0],
                "expected": " ".join(e),
                "actual": " ".join(a),
                "run": ridx,
                "algorithm": m.get("algorithm"),
                "feedback": m.get("feedback"),
            }
            if e and a and e[0] == "E" == a[0]:
                rec["kind"] = "eval"
                # eval index within the run: E records since the run's
                # A marker on the expected side (the scripted source's t).
                idx = 0
                for j in range(k - 1, -1, -1):
                    tag = expected_rows[j][1][0]
                    if tag == "A":
                        break
                    if tag == "E":
                        idx += 1
                rec["eval_index"] = idx
                rec["op_expected"] = int(e[1], 16)
                rec["op_actual"] = int(a[1], 16)
            else:
                rec["kind"] = e[0] if e else "?"
            first = rec
    # a run whose record region shifted (a mutant that changes gating
    # changes the eval count) misaligns everything after the break; every
    # shifted record counts as a mismatch of the run that owns it, which
    # is the honest verdict for a structurally broken stream.
    return count, first, per_run


